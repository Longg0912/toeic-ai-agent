
"""Persistent ChromaDB vector store for TOEIC RAG."""

from __future__ import annotations

import math
import os

from collections.abc import Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any


DEFAULT_COLLECTION_NAME = "toeic_chunks"

PROJECT_ROOT = Path(__file__).resolve().parents[3]

DEFAULT_PERSIST_DIRECTORY = (
    PROJECT_ROOT / "data" / "chroma"
)


class VectorStoreConfigurationError(RuntimeError):
    """Raised when vector store configuration is invalid."""


class VectorStoreError(RuntimeError):
    """Raised when ChromaDB cannot complete an operation."""


@dataclass(frozen=True)
class ChunkVectorRecord:
    """A document chunk prepared for vector storage."""

    vector_id: str
    document_id: str
    chunk_index: int
    content: str
    page_number: int | None = None
    content_hash: str | None = None


@dataclass(frozen=True)
class VectorSearchResult:
    """A chunk returned by semantic vector search."""

    vector_id: str
    content: str
    metadata: dict[str, Any] = field(default_factory=dict)
    distance: float | None = None


def _load_chroma_collection(
    persist_directory: Path,
    collection_name: str,
) -> tuple[Any, Any]:
    """Create a persistent Chroma client and get its collection."""

    try:
        import chromadb
    except ImportError as exc:
        raise VectorStoreConfigurationError(
            "ChromaDB is not installed. "
            "Install dependencies from requirements.txt."
        ) from exc

    try:
        persist_directory.mkdir(
            parents=True,
            exist_ok=True,
        )

        client = chromadb.PersistentClient(
            path=str(persist_directory),
        )

        collection = client.get_or_create_collection(
            name=collection_name,
            metadata={"hnsw:space": "cosine"},
            embedding_function=None,
        )

        return client, collection

    except Exception as exc:
        raise VectorStoreError(
            "Could not initialize the ChromaDB collection."
        ) from exc


class ChromaVectorStore:
    """Store and search precomputed embeddings in ChromaDB.

    Embeddings are generated by EmbeddingService.
    ChromaDB only stores and retrieves the supplied vectors.
    """

    def __init__(
        self,
        persist_directory: str | Path | None = None,
        collection_name: str | None = None,
        collection: Any | None = None,
    ) -> None:
        configured_directory = (
            persist_directory
            or os.getenv("CHROMA_PERSIST_DIRECTORY")
            or DEFAULT_PERSIST_DIRECTORY
        )

        configured_collection = (
            collection_name
            or os.getenv("CHROMA_COLLECTION_NAME")
            or DEFAULT_COLLECTION_NAME
        )

        if not str(configured_collection).strip():
            raise VectorStoreConfigurationError(
                "collection_name must not be empty."
            )

        self.persist_directory = Path(
            configured_directory
        ).expanduser()

        self.collection_name = str(
            configured_collection
        ).strip()

        # Dependency injection makes testing possible
        # without starting a real ChromaDB instance.
        self._collection = collection
        self._client = None

    def _get_collection(self) -> Any:
        """Initialize the persistent collection only when needed."""

        if self._collection is None:
            self._client, self._collection = (
                _load_chroma_collection(
                    persist_directory=self.persist_directory,
                    collection_name=self.collection_name,
                )
            )

        return self._collection

    @staticmethod
    def _validate_chunks(
        chunks: Sequence[ChunkVectorRecord],
    ) -> list[ChunkVectorRecord]:
        """Validate chunk records before writing."""

        if isinstance(chunks, (str, bytes)):
            raise ValueError(
                "chunks must be a sequence of ChunkVectorRecord."
            )

        validated = list(chunks)

        for index, chunk in enumerate(validated):
            if not isinstance(chunk, ChunkVectorRecord):
                raise ValueError(
                    f"Chunk at index {index} has an invalid type."
                )

            if not chunk.vector_id.strip():
                raise ValueError(
                    f"Chunk at index {index} has an empty vector_id."
                )

            if not chunk.document_id.strip():
                raise ValueError(
                    f"Chunk at index {index} has an empty document_id."
                )

            if chunk.chunk_index < 0:
                raise ValueError(
                    f"Chunk at index {index} has an invalid chunk_index."
                )

            if chunk.page_number is not None:
                if (
                    not isinstance(chunk.page_number, int)
                    or isinstance(chunk.page_number, bool)
                    or chunk.page_number < 1
                ):
                    raise ValueError(
                        f"Chunk at index {index} has an invalid page_number."
                    )

            if not isinstance(chunk.content, str) or not chunk.content.strip():
                raise ValueError(
                    f"Chunk at index {index} has empty content."
                )

        vector_ids = [
            chunk.vector_id
            for chunk in validated
        ]

        if len(vector_ids) != len(set(vector_ids)):
            raise ValueError(
                "Chunk vector_id values must be unique in one batch."
            )

        return validated

    @staticmethod
    def _validate_embeddings(
        embeddings: Sequence[Sequence[float]],
        expected_count: int,
    ) -> list[list[float]]:
        """Validate embedding count, dimensions and numeric values."""

        if hasattr(embeddings, "tolist"):
            embeddings = embeddings.tolist()

        if not isinstance(embeddings, (list, tuple)):
            raise ValueError(
                "embeddings must be a sequence of vectors."
            )

        if len(embeddings) != expected_count:
            raise ValueError(
                "The number of embeddings must match the number of chunks."
            )

        vectors: list[list[float]] = []
        expected_dimension: int | None = None

        for index, raw_vector in enumerate(embeddings):
            if hasattr(raw_vector, "tolist"):
                raw_vector = raw_vector.tolist()

            if not isinstance(raw_vector, (list, tuple)):
                raise ValueError(
                    f"Embedding at index {index} has an invalid format."
                )

            if not raw_vector:
                raise ValueError(
                    f"Embedding at index {index} is empty."
                )

            try:
                vector = [
                    float(value)
                    for value in raw_vector
                ]
            except (TypeError, ValueError) as exc:
                raise ValueError(
                    f"Embedding at index {index} contains invalid values."
                ) from exc

            if not all(math.isfinite(value) for value in vector):
                raise ValueError(
                    f"Embedding at index {index} contains "
                    "NaN or infinite values."
                )

            if expected_dimension is None:
                expected_dimension = len(vector)

            elif len(vector) != expected_dimension:
                raise ValueError(
                    "All embeddings in a batch must have "
                    "the same dimension."
                )

            norm = math.sqrt(
                sum(value * value for value in vector)
            )

            if norm == 0:
                raise ValueError(
                    f"Embedding at index {index} has zero magnitude."
                )

            vectors.append(vector)

        return vectors

    @staticmethod
    def _build_metadata(
        chunk: ChunkVectorRecord,
    ) -> dict[str, str | int]:
        """Build metadata using Chroma-supported scalar values."""

        metadata: dict[str, str | int] = {
            "document_id": chunk.document_id,
            "chunk_index": chunk.chunk_index,
        }

        if chunk.page_number is not None:
            metadata["page_number"] = chunk.page_number

        if chunk.content_hash is not None:
            metadata["content_hash"] = chunk.content_hash

        return metadata

    def upsert_chunks(
        self,
        chunks: Sequence[ChunkVectorRecord],
        embeddings: Sequence[Sequence[float]],
    ) -> int:
        """Insert or update chunks and their precomputed embeddings."""

        validated_chunks = self._validate_chunks(chunks)

        if not validated_chunks:
            if len(embeddings) != 0:
                raise ValueError(
                    "Embeddings must be empty when chunks are empty."
                )
            return 0

        vectors = self._validate_embeddings(
            embeddings=embeddings,
            expected_count=len(validated_chunks),
        )

        ids = [
            chunk.vector_id
            for chunk in validated_chunks
        ]

        documents = [
            chunk.content.strip()
            for chunk in validated_chunks
        ]

        metadatas = [
            self._build_metadata(chunk)
            for chunk in validated_chunks
        ]

        collection = self._get_collection()

        try:
            collection.upsert(
                ids=ids,
                embeddings=vectors,
                documents=documents,
                metadatas=metadatas,
            )
        except Exception as exc:
            raise VectorStoreError(
                "Could not upsert chunks into ChromaDB."
            ) from exc

        return len(validated_chunks)

    def search(
        self,
        query_embedding: Sequence[float],
        top_k: int = 5,
        document_id: str | None = None,
    ) -> list[VectorSearchResult]:
        """Find the nearest chunks for one query embedding."""

        if (
            not isinstance(top_k, int)
            or isinstance(top_k, bool)
            or top_k <= 0
        ):
            raise ValueError(
                "top_k must be a positive integer."
            )

        query_vector = self._validate_embeddings(
            embeddings=[query_embedding],
            expected_count=1,
        )[0]

        collection = self._get_collection()

        try:
            total_count = collection.count()

            if total_count == 0:
                return []

            filters = None

            if document_id is not None:
                if not document_id.strip():
                    raise ValueError(
                        "document_id must not be empty."
                    )

                filters = {
                    "document_id": document_id,
                }

            response = collection.query(
                query_embeddings=[query_vector],
                n_results=min(top_k, total_count),
                where=filters,
                include=[
                    "documents",
                    "metadatas",
                    "distances",
                ],
            )

        except ValueError:
            raise

        except Exception as exc:
            raise VectorStoreError(
                "Could not search vectors in ChromaDB."
            ) from exc

        ids = response.get("ids", [[]])
        documents = response.get("documents", [[]])
        metadatas = response.get("metadatas", [[]])
        distances = response.get("distances", [[]])

        result_ids = ids[0] if ids else []
        result_documents = documents[0] if documents else []
        result_metadatas = metadatas[0] if metadatas else []
        result_distances = distances[0] if distances else []

        results: list[VectorSearchResult] = []

        for index, vector_id in enumerate(result_ids):
            content = (
                result_documents[index]
                if index < len(result_documents)
                else ""
            )

            metadata = (
                result_metadatas[index]
                if index < len(result_metadatas)
                else {}
            )

            distance = (
                result_distances[index]
                if index < len(result_distances)
                else None
            )

            results.append(
                VectorSearchResult(
                    vector_id=vector_id,
                    content=content or "",
                    metadata=metadata or {},
                    distance=(
                        float(distance)
                        if distance is not None
                        else None
                    ),
                )
            )

        return results

    def delete_document(
        self,
        document_id: str,
    ) -> int:
        """Delete all vectors belonging to one document."""

        if not isinstance(document_id, str) or not document_id.strip():
            raise ValueError(
                "document_id must not be empty."
            )

        collection = self._get_collection()

        try:
            existing = collection.get(
                where={
                    "document_id": document_id,
                },
                include=[],
            )

            existing_ids = existing.get("ids", [])

            if not existing_ids:
                return 0

            collection.delete(
                where={
                    "document_id": document_id,
                },
            )

            return len(existing_ids)

        except Exception as exc:
            raise VectorStoreError(
                "Could not delete document vectors from ChromaDB."
            ) from exc

    def count(self) -> int:
        """Return the number of vectors in the collection."""

        try:
            return int(
                self._get_collection().count()
            )
        except Exception as exc:
            raise VectorStoreError(
                "Could not count vectors in ChromaDB."
            ) from exc
